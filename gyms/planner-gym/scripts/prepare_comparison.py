"""Prepare isolated planner configs and a resource-bounded batch plan; never run them."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
import os
from collections import Counter
from pathlib import Path

import yaml
from autoscaling_arena.match_config import load_match_config

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "configs/60traces"
REFERENCE = ROOT / "data/60traces/reproduction/reference/baseline-results.json"
NAMES = {
    "mpc": "MPC",
    "planner": "Dynamo",
    "keda": "KEDA",
    "reactive": "Reactive",
    "jev": "JEV",
}
HEADER = (
    "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Generated by scripts/prepare_comparison.py; do not edit.\n\n"
)


def build_jobs(catalog: dict, references: list[dict], policy: dict) -> list[dict]:
    """Select cases and reserve memory from measured static reference peaks."""
    rows = {row["benchmark_id"]: row for row in references}
    parallel = policy["parallel"]
    jobs = []
    for case in catalog["cases"]:
        case_id = case["case_id"]
        reference = rows[case_id]
        if reference["trace_sha256"] != case["trace_sha256"]:
            raise ValueError(f"{case_id}: reference trace hash differs from catalog")
        memory = max(
            parallel["minimum_memory_gib"],
            math.ceil(
                reference["peak_rss_gib"] * parallel["memory_multiplier"]
                + parallel["extra_memory_gib"]
            ),
        )
        for planner in policy["planners"]:
            if planner not in NAMES:
                raise ValueError(f"unknown comparison planner: {planner}")
            if (
                planner == "jev"
                and case["test_duration_s"]
                >= policy["jev"]["exclude_duration_at_least_s"]
            ):
                continue
            api_timeout = policy["jev"]["max_calls"] * 5 if planner == "jev" else 0
            jobs.append(
                {
                    "id": f"{case_id}-{planner}",
                    "case_id": case_id,
                    "group": case_id[:4],
                    "planner": planner,
                    "duration_s": case["test_duration_s"],
                    "trace_sha256": case["trace_sha256"],
                    "reference_peak_rss_gib": reference["peak_rss_gib"],
                    "memory_gib": memory,
                    "cores": parallel["cores_per_run"],
                    "exclusive": memory >= parallel["exclusive_at_memory_gib"],
                    "timeout_s": max(
                        3600,
                        math.ceil(reference["simulation_wall_s"] * 10 + api_timeout),
                    ),
                    "max_calls": policy["jev"]["max_calls"] if planner == "jev" else 0,
                }
            )
    return jobs


def schedule_batches(
    jobs: list[dict], parallel: dict
) -> tuple[list[list[dict]], list[dict]]:
    """First-fit decreasing reservations; a batch finishes before the next starts.

    Oversized jobs remain explicitly blocked, never silently dropped. Core slots
    describe physical cores; the launch host must map them to allowed CPU IDs.
    """
    memory = parallel["memory_gib"] - parallel["reserve_memory_gib"]
    cores = parallel["physical_cores"] - parallel["reserve_cores"]
    if memory <= 0 or cores < parallel["cores_per_run"]:
        raise ValueError("host has no capacity after reserving OS/controller resources")
    pending = sorted(jobs, key=lambda job: (-job["memory_gib"], job["id"]))
    blocked = [
        job for job in pending if job["memory_gib"] > memory or job["cores"] > cores
    ]
    pending = [job for job in pending if job not in blocked]
    batches = []
    while pending:
        batch = []
        used_memory = used_cores = jev_count = 0
        for job in pending:
            if batch and (job["exclusive"] or batch[0]["exclusive"]):
                continue
            if len(batch) >= parallel["max_parallel_runs"]:
                break
            if job["planner"] == "jev" and jev_count >= parallel["max_parallel_jev"]:
                continue
            if (
                used_memory + job["memory_gib"] > memory
                or used_cores + job["cores"] > cores
            ):
                continue
            batch.append(job)
            used_memory += job["memory_gib"]
            used_cores += job["cores"]
            jev_count += job["planner"] == "jev"
        if not batch:
            raise ValueError("parallel policy cannot schedule any remaining job")
        batches.append(batch)
        selected = {job["id"] for job in batch}
        pending = [job for job in pending if job["id"] not in selected]
    return batches, blocked


def make_config(
    base: dict, job: dict, policy: dict, config_path: Path, output: Path
) -> dict:
    """Preserve the static case's input/SLO/start and add the chosen dynamic policy."""
    config = copy.deepcopy(base)
    backend = config["backend"]
    disagg = backend["topology"] == "disagg"
    limits = policy["worker_limits"]
    maximum = limits["max_total"]
    minimum = limits["min_total"]
    if disagg and minimum != 2:
        raise ValueError("this comparison requires a 1P+1D minimum")
    static = backend["autoscalers"][0]["config"]
    start = {"decode": static["num_decode"]}
    if disagg:
        start["prefill"] = static["num_prefill"]
    engines = backend["engines"]
    p_cost = (
        engines["prefill"]["tp_size"] * engines["prefill"].get("attention_dp_size", 1)
        if disagg
        else 0
    )
    decode = engines["decode" if disagg else "aggregate"]
    d_cost = decode["tp_size"] * decode.get("attention_dp_size", 1)
    # Allow every split with >=1 worker per active pool, including 15P+1D/1P+15D.
    backend["gpu_budget"] = (
        max(p_cost * (maximum - 1) + d_cost, p_cost + d_cost * (maximum - 1))
        if disagg
        else maximum * d_cost
    )
    backend["worker_limits"] = dict(limits)
    planner = job["planner"]
    bounds = {
        "min_decode": 1 if disagg else minimum,
        "max_decode": maximum - 1 if disagg else maximum,
    }
    if disagg:
        bounds.update(min_prefill=1, max_prefill=maximum - 1)
    parameters = bounds if planner in {"keda", "reactive", "jev"} else {}
    if planner == "jev":
        parameters.update(
            max_calls=policy["jev"]["max_calls"],
            poll_interval_s=policy["jev"]["poll_interval_s"],
        )
    if planner == "mpc":
        profile = config["slo_profiles"][0]
        parameters = {
            "forward_model": "ais",
            "min_replicas": 1 if disagg else minimum,
            "max_replicas": maximum - 1 if disagg else maximum,
            "slo_ttft_ms": profile["ttft_ms"],
            "slo_itl_ms": profile["itl_ms"],
            "cold_start_s": decode["runtime"]["cold_start_delay_s"],
        }
    if planner == "planner":
        backend["planner_config"] = {"min_endpoint": 1 if disagg else minimum}
    backend["autoscalers"] = [
        {"name": NAMES[planner], "type": planner, "start": start, "config": parameters}
    ]
    config["name"] = job["id"]
    config[
        "description"
    ] = "Non-learning comparison with a shared 2–16 total-worker target range."
    config["labels"].update(comparison="60traces-nonlearning", planner=planner)
    for trace in config["evaluations"]["traces"]:
        if "path" in trace:
            trace["path"] = os.path.relpath(
                (SOURCE / trace["path"]).resolve(), config_path.parent
            )
        if "paths" in trace:
            trace["paths"] = [
                os.path.relpath((SOURCE / path).resolve(), config_path.parent)
                for path in trace["paths"]
            ]
    config["execution"].update(
        max_parallel_runs=1,
        timeout_s=job["timeout_s"],
        max_memory_mb=(job["memory_gib"] - 1) * 1024,
    )
    result_dir = output / "results" / job["case_id"] / planner

    def relative(path: Path) -> str:
        return os.path.relpath(path, config_path.parent)

    config["publish"] = {
        "artifact_root": relative(result_dir / "artifacts"),
        "destinations": [
            {"type": "json", "path": relative(result_dir / "results.json")}
        ],
    }
    return config


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", type=Path, default=SOURCE / "comparison.yaml")
    parser.add_argument(
        "--output", type=Path, default=ROOT / "runs/60traces-comparison"
    )
    parser.add_argument(
        "--memory-gib", type=int, help="override launch-host RAM for planning"
    )
    parser.add_argument(
        "--physical-cores", type=int, help="override launch-host physical cores"
    )
    args = parser.parse_args()
    output = args.output.resolve()
    policy = yaml.safe_load(args.policy.read_text())
    parallel = policy["parallel"]
    if args.memory_gib is not None:
        parallel["memory_gib"] = args.memory_gib
        parallel["reserve_memory_gib"] = max(8, math.ceil(args.memory_gib / 8))
    if args.physical_cores is not None:
        parallel["physical_cores"] = args.physical_cores
    catalog = json.loads((SOURCE / "catalog.json").read_text())
    references = json.loads(REFERENCE.read_text())
    jobs = build_jobs(catalog, references, policy)
    for job in jobs:
        path = output / "configs" / job["case_id"] / f"{job['planner']}.yaml"
        base = yaml.safe_load((SOURCE / f"{job['case_id']}.yaml").read_text())
        config = make_config(base, job, policy, path, output)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(HEADER + yaml.safe_dump(config, sort_keys=False))
        resolved = load_match_config(path)
        if resolved.expected_runs != 1:
            raise ValueError(f"{job['id']}: expected exactly one isolated run")
        job["config"] = str(path.relative_to(output))
        job["config_sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
        job["session"] = f"sessions/{job['case_id']}/{job['planner']}"
    batches, blocked = schedule_batches(jobs, parallel)
    plan = {
        "schema_version": 1,
        "generated_by": "scripts/prepare_comparison.py; do not edit",
        "policy": policy,
        "static_reference": os.path.relpath(REFERENCE, output),
        "static_reference_rows": len(references),
        "new_runs": len(jobs),
        "runs_by_planner": dict(Counter(job["planner"] for job in jobs)),
        "max_jev_calls": sum(job["max_calls"] for job in jobs),
        "jobs": jobs,
        "batches": [[job["id"] for job in batch] for batch in batches],
        "blocked_jobs": [job["id"] for job in blocked],
        "notes": [
            "Planning only: no simulator or API has been called.",
            "Use Linux native replay; CPU affinity must bind two distinct physical cores per concurrent run.",
            "Resource reservations are estimates. The RSS guard fails a run that exceeds its allowance.",
            "Keep JEV out of full-15-case rankings; compare all five planners on the shared seven short cases per group.",
            "Reference static scores require runtime/scoring provenance checks before merging into new leaderboards.",
        ],
    }
    (output / "plan.json").write_text(json.dumps(plan, indent=2) + "\n")
    print(
        f"Prepared {len(jobs)} runs in {len(batches)} batches; {len(blocked)} blocked by host resources."
    )
    print(
        f"JEV: {plan['runs_by_planner']['jev']} runs, at most {plan['max_jev_calls']} calls total."
    )
    print(output / "plan.json")


if __name__ == "__main__":
    main()
