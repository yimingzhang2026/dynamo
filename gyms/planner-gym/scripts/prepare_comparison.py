"""Prepare isolated planner configs and a resource-bounded batch plan; never run them."""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
import math
import os
from collections import Counter
from pathlib import Path

import yaml
from autoscaling_arena.match_config import load_match_config
from autoscaling_arena.resource_policy import (
    apply_case_resources,
    case_resources,
    resource_policy_description,
)

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "configs/60traces"
REFERENCE = ROOT / "leaderboards/60traces/inputs/static-latency.json"
NAMES = {
    "mpc": "cloudAI-MPC",
    "planner": "Dynamo",
    "keda": "KEDA",
    "reactive": "Reactive",
    "static": "Static",
    "knowline31b": "KnowLine-31B",
}
HEADER = (
    "# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.\n"
    "# SPDX-License-Identifier: Apache-2.0\n"
    "# Generated by scripts/prepare_comparison.py; do not edit.\n\n"
)


def load_references(path: Path = REFERENCE) -> list[dict]:
    """Use the current validated Static measurements for resource reservations."""
    references = []
    for record in json.loads(path.read_text())["records"]:
        row = record["result"]
        if row["status"] != "completed":
            raise ValueError("Resource planning requires all current Static results")
        references.append(
            {
                "benchmark_id": row["case_id"],
                "trace_sha256": row["inputs"]["trace_sha256"],
                "peak_rss_gib": row["execution"]["peak_rss_gib"],
                "simulation_wall_s": row["execution"]["wall_time_s"],
            }
        )
    return references


def build_jobs(catalog: dict, references: list[dict], policy: dict) -> list[dict]:
    """Select cases and reserve memory from measured static reference peaks."""
    rows = {row["benchmark_id"]: row for row in references}
    parallel = policy["parallel"]
    jobs = []
    for case in catalog["cases"]:
        case_id = case["case_id"]
        resources = case_resources(
            yaml.safe_load((SOURCE / f"{case_id}.yaml").read_text()), policy
        )
        reference = rows[case_id]
        if reference["trace_sha256"] != case["trace_sha256"]:
            raise ValueError(f"{case_id}: reference trace hash differs from catalog")
        memory = max(
            parallel["minimum_memory_gib"],
            math.ceil(
                reference["peak_rss_gib"] * parallel["memory_multiplier"]
                + parallel["extra_memory_gib"]
            ),
        )
        for planner in policy["planners"]:
            if planner not in NAMES:
                raise ValueError(f"unknown comparison planner: {planner}")
            jobs.append(
                {
                    "id": f"{case_id}-{planner}",
                    "case_id": case_id,
                    "group": case_id[:4],
                    "planner": planner,
                    "resources": resources,
                    "duration_s": case["test_duration_s"],
                    "trace_sha256": case["trace_sha256"],
                    "reference_peak_rss_gib": reference["peak_rss_gib"],
                    "memory_gib": memory,
                    "cores": parallel["cores_per_run"],
                    "exclusive": memory >= parallel["exclusive_at_memory_gib"],
                    "timeout_s": max(
                        policy.get("timeout_s", 86400),
                        math.ceil(reference["simulation_wall_s"] * 10),
                    ),
                    "max_calls": (
                        policy["knowline"]["max_calls"]
                        if planner == "knowline31b"
                        else 0
                    ),
                }
            )
    return jobs


def schedule_batches(
    jobs: list[dict], parallel: dict
) -> tuple[list[list[dict]], list[dict]]:
    """First-fit decreasing reservations; a batch finishes before the next starts.

    Oversized jobs remain explicitly blocked, never silently dropped. Core slots
    describe physical cores; the launch host must map them to allowed CPU IDs.
    """
    memory = parallel["memory_gib"] - parallel["reserve_memory_gib"]
    cores = parallel["physical_cores"] - parallel["reserve_cores"]
    if memory <= 0 or cores < parallel["cores_per_run"]:
        raise ValueError("host has no capacity after reserving OS/controller resources")
    pending = sorted(jobs, key=lambda job: (-job["memory_gib"], job["id"]))
    blocked = [
        job for job in pending if job["memory_gib"] > memory or job["cores"] > cores
    ]
    pending = [job for job in pending if job not in blocked]
    batches = []
    while pending:
        batch = []
        used_memory = used_cores = model_count = 0
        for job in pending:
            if batch and (job["exclusive"] or batch[0]["exclusive"]):
                continue
            if len(batch) >= parallel["max_parallel_runs"]:
                break
            if (
                job["planner"] == "knowline31b"
                and model_count >= parallel["max_parallel_decision_models"]
            ):
                continue
            if (
                used_memory + job["memory_gib"] > memory
                or used_cores + job["cores"] > cores
            ):
                continue
            batch.append(job)
            used_memory += job["memory_gib"]
            used_cores += job["cores"]
            model_count += job["planner"] == "knowline31b"
        if not batch:
            raise ValueError("parallel policy cannot schedule any remaining job")
        batches.append(batch)
        selected = {job["id"] for job in batch}
        pending = [job for job in pending if job["id"] not in selected]
    return batches, blocked


def select_jobs(jobs: list[dict], selected: list[str]) -> list[dict]:
    """Select an exact nonempty subset without silently dropping unknown IDs."""
    if not selected or len(selected) != len(set(selected)):
        raise ValueError("Selection must contain distinct job IDs")
    unknown = set(selected) - {job["id"] for job in jobs}
    if unknown:
        raise ValueError(f"Unknown selected jobs: {sorted(unknown)}")
    return [job for job in jobs if job["id"] in set(selected)]


def make_config(
    base: dict,
    job: dict,
    policy: dict,
    config_path: Path,
    output: Path,
) -> dict:
    """Preserve input, SLO and initial fleet; apply the shared resource contract."""
    config = copy.deepcopy(base)
    # Preserve the static baseline's complete offered window even when every
    # request finishes early. Charge the final fleet during the unused tail;
    # do not shorten the window or fabricate post-replay controller decisions.
    config["evaluations"]["defaults"]["measurement_window"][
        "idle_tail_policy"
    ] = "hold_final"
    backend = config["backend"]
    disagg = backend["topology"] == "disagg"
    resources = apply_case_resources(config, policy)
    if job["resources"] != resources:
        raise ValueError("Planned resource policy differs from generated configuration")
    static = backend["autoscalers"][0]["config"]
    start = {"decode": static["num_decode"]}
    if disagg:
        start["prefill"] = static["num_prefill"]
    identity = job["planner"]
    planner = "jev" if identity == "knowline31b" else identity
    bounds = {
        "min_decode": resources["min_workers"]["decode" if disagg else "aggregate"],
        "max_decode": resources["max_workers"]["decode" if disagg else "aggregate"],
    }
    if disagg:
        bounds.update(min_prefill=1, max_prefill=resources["max_workers"]["prefill"])
    parameters = bounds if planner in {"keda", "reactive", "jev"} else {}
    if identity == "knowline31b":
        parameters.update(policy["knowline"])
        parameters.pop("revision")
        config["labels"]["model_revision"] = policy["knowline"]["revision"]
    if planner == "static":
        parameters = dict(static)
        backend.pop("worker_limits", None)
    if planner == "mpc":
        profile = config["slo_profiles"][0]
        decode = backend["engines"]["decode" if disagg else "aggregate"]
        parameters = {
            "forward_model": "ais",
            "min_replicas": min(resources["min_workers"].values()),
            "max_replicas": max(resources["max_workers"].values()),
            "slo_ttft_ms": profile["ttft_ms"],
            "slo_itl_ms": profile["itl_ms"],
            "cold_start_s": decode["runtime"]["cold_start_delay_s"],
        }
    if planner == "planner":
        backend["planner_config"] = {
            "min_endpoint": min(resources["min_workers"].values())
        }
    backend["autoscalers"] = [
        {"name": NAMES[identity], "type": planner, "start": start, "config": parameters}
    ]
    backend["replay"].update(request_capture="jsonl")
    backend.setdefault("planner_config", {}).update(
        report_interval_hours=None, live_dashboard_port=0
    )
    if planner == "static":
        backend["autoscalers"][0].pop("start")
    config["name"] = job["id"]
    config[
        "description"
    ] = f"Full-trace evaluation with a GPU ceiling of {resource_policy_description(resources)} and unchanged initial fleet."
    config["labels"].update(comparison="60traces", planner=identity)
    for trace in config["evaluations"]["traces"]:
        if "path" in trace:
            trace["path"] = os.path.relpath(
                (SOURCE / trace["path"]).resolve(), config_path.parent
            )
        if "paths" in trace:
            trace["paths"] = [
                os.path.relpath((SOURCE / path).resolve(), config_path.parent)
                for path in trace["paths"]
            ]
    config["execution"].update(
        max_parallel_runs=1,
        timeout_s=job["timeout_s"],
        max_memory_mb=(job["memory_gib"] - 1) * 1024,
    )
    result_dir = output / "results" / job["case_id"] / identity

    def relative(path: Path) -> str:
        return os.path.relpath(path, config_path.parent)

    config["publish"] = {
        "artifact_root": relative(result_dir / "artifacts"),
        "destinations": [
            {"type": "json", "path": relative(result_dir / "results.json")}
        ],
    }
    return config


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", type=Path, default=SOURCE / "comparison.yaml")
    parser.add_argument(
        "--output", type=Path, default=ROOT / "runs/60traces-comparison"
    )
    parser.add_argument(
        "--memory-gib", type=int, help="override launch-host RAM for planning"
    )
    parser.add_argument(
        "--physical-cores", type=int, help="override launch-host physical cores"
    )
    parser.add_argument(
        "--selection", type=Path, help="JSON list of exact job IDs to prepare"
    )
    args = parser.parse_args()
    output = args.output.resolve()
    if (output / "plan.json").exists():
        raise FileExistsError(
            "Campaign already prepared; choose a new output directory"
        )
    policy = yaml.safe_load(args.policy.read_text())
    parallel = policy["parallel"]
    if args.memory_gib is not None:
        parallel["memory_gib"] = args.memory_gib
        parallel["reserve_memory_gib"] = max(8, math.ceil(args.memory_gib / 8))
    if args.physical_cores is not None:
        parallel["physical_cores"] = args.physical_cores
    catalog = json.loads((SOURCE / "catalog.json").read_text())
    references = load_references()
    jobs = build_jobs(catalog, references, policy)
    if args.selection is not None:
        jobs = select_jobs(jobs, json.loads(args.selection.read_text()))
    for job in jobs:
        path = output / "configs" / job["case_id"] / f"{job['planner']}.yaml"
        base = yaml.safe_load((SOURCE / f"{job['case_id']}.yaml").read_text())
        config = make_config(base, job, policy, path, output)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(HEADER + yaml.safe_dump(config, sort_keys=False))
        resolved = load_match_config(path)
        if resolved.expected_runs != 1:
            raise ValueError(f"{job['id']}: expected exactly one isolated run")
        job["config"] = str(path.relative_to(output))
        job["config_sha256"] = hashlib.sha256(path.read_bytes()).hexdigest()
        job["session"] = f"sessions/{job['case_id']}/{job['planner']}"
    batches, blocked = schedule_batches(jobs, parallel)
    plan = {
        "schema_version": 1,
        "generated_by": "scripts/prepare_comparison.py; do not edit",
        "policy": policy,
        "static_reference": os.path.relpath(REFERENCE, output),
        "static_reference_rows": len(references),
        "new_runs": len(jobs),
        "runs_by_planner": dict(Counter(job["planner"] for job in jobs)),
        "max_model_calls": sum(job["max_calls"] for job in jobs),
        "jobs": jobs,
        "batches": [[job["id"] for job in batch] for batch in batches],
        "blocked_jobs": [job["id"] for job in blocked],
        "notes": [
            "Planning only: no simulator or API has been called.",
            "Linux replay uses the configured CPU affinity and memory reservations.",
            "Resource reservations are estimates. The RSS guard fails a run that exceeds its allowance.",
            "Main ranks use cloudAI-MPC, Dynamo, KEDA, Reactive, Static and KnowLine on 60 traces.",
            "Current validated Static replays supply scores and execution RAM estimates.",
        ],
    }
    (output / "plan.json").write_text(json.dumps(plan, indent=2) + "\n")
    print(
        f"Prepared {len(jobs)} runs in {len(batches)} batches; {len(blocked)} blocked by host resources."
    )
    print(
        f"KnowLine: {plan['runs_by_planner'].get('knowline31b', 0)} runs, at most {plan['max_model_calls']} local model calls."
    )
    print(output / "plan.json")


if __name__ == "__main__":
    main()
